"""Slide grammar from vision labels of archive slides (analysis/grammar/labels_*.json, form in analysis/grammar/SCHEMA.md).

Writes analysis/grammar.json (numbers for compose.py) and brain/30-patterns/*.md (short notes Claude reads instead of copying slides).
The archive is a library of elements and how they connect (user ruling 2026-11-06 / 2026-11-12): this counts how sections, blocks,
headers, intros, grey boxes, dividers and connectors combine, never whole layouts.
Run: py -3 -I tools/grammar.py            (stats + notes)
     py -3 -I tools/grammar.py --agree    (labels_1.json vs the reference verify_1.json)
"""
import json, sys, glob, collections
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GD = ROOT / "analysis" / "grammar"; OUT = ROOT / "analysis" / "grammar.json"; NOTES = ROOT / "brain" / "30-patterns"
HEAD = "# Generated by tools/grammar.py — do not edit by hand\n\n"


def fam(b):
    return b.split(":")[0]


def load():
    meta = {e["id"]: e for f in sorted(GD.glob("batch_*.json")) for e in json.loads(f.read_text("utf8"))}
    labs = [l for f in sorted(GD.glob("labels_*.json")) for l in json.loads(f.read_text("utf8"))]
    for l in labs:
        m = meta.get(l["id"], {}); l["ref"] = f"{m.get('deck', '?')}#{m.get('slide', '?')}"; l["deck"] = m.get("deck", "?")
        l["sections"] = [s for s in l.get("sections") or [] if isinstance(s, dict)]
        for s in l["sections"]: s["blocks"] = [b for b in s.get("blocks") or [] if isinstance(b, str)]
    return labs


class Tally:
    """Counts with evidence spread over decks (round-robin by deck, not alphabetical: one deck must not fill every row)."""
    def __init__(s): s.n = collections.Counter(); s.ev = collections.defaultdict(lambda: collections.defaultdict(list))
    def add(s, k, lab, w=1): s.n[k] += w; s.ev[k][lab["deck"]].append(lab["ref"])
    def refs(s, k, m=3):
        decks = list(s.ev[k].values()); out = []
        while len(out) < m and any(decks):
            for d in decks:
                if d and len(out) < m: out.append(d.pop(0))
        return out
    def rows(s, tot, top=10):
        return [(k, v, v / max(tot, 1), s.refs(k)) for k, v in s.n.most_common(top)]


def stats(labs):
    N = len(labs); secs = [(l, s) for l in labs for s in l["sections"]]; S = len(secs)
    T = {k: Tally() for k in ("grid", "nsec", "split2", "split3", "header", "under", "top", "nblocks", "grey_kind", "grey_pos", "full", "conn", "pair")}
    widths = collections.defaultdict(list); kind_sec = collections.Counter(); grey_kind = collections.Counter(); blocks_vs_secs = collections.defaultdict(collections.Counter)
    intro = hdr = grey = 0; vdiv = vmulti = hdiv = hstack = 0
    for l in labs:
        ss = l["sections"]; n = len(ss); T["grid"].add(l.get("grid", "?"), l); T["nsec"].add(str(min(n, 4)) + ("+" if n >= 4 else ""), l)
        nb = sum(len(s["blocks"]) for s in ss); blocks_vs_secs[min(nb, 7)][min(n, 4)] += 1
        row1 = [s for s in ss if s.get("row", 1) == 1]
        if l.get("grid") == "columns" and len(row1) == 2:
            nar = min(s.get("w", 50) for s in row1) / max(sum(s.get("w", 50) for s in row1), 1)
            T["split2"].add("equal (45-50%)" if nar >= .45 else "40-45%" if nar >= .4 else "30-40%" if nar >= .3 else "<30%", l)
        if l.get("grid") == "columns" and len(row1) == 3:
            ws = [s.get("w", 33) for s in row1]; T["split3"].add("equal" if max(ws) - min(ws) <= 8 else f"widest {['left', 'middle', 'right'][ws.index(max(ws))]}", l)
        for i, s in enumerate(ss):
            fams = [fam(b) for b in s["blocks"]]
            if s.get("header", "none") != "none": hdr += 1
            T["header"].add(s.get("header", "none"), l); intro += bool(s.get("intro")); T["nblocks"].add(str(min(len(fams), 4)), l)
            if fams: T["top"].add(fams[0], l)
            for a, b in zip(fams, fams[1:]): T["under"].add(f"{a} -> {b}", l)
            for a in set(fams):
                kind_sec[a] += 1
                if s.get("grey_box"): grey_kind[a] += 1
                if row1 and s in row1 and n > 1: widths[a].append(s.get("w", 100 / len(row1)) * len(row1) / 100)   # 1.0 = an equal share
            for j, a in enumerate(fams):
                for b in fams[j + 1:]: T["pair"].add(" + ".join(sorted((a, b))), l)
            if s.get("grey_box"):
                grey += 1; T["grey_pos"].add("only" if n == 1 else "first" if i == 0 else "last" if i == n - 1 else "middle", l)
                for a in set(fams): T["grey_kind"].add(a, l)
        for f in l.get("full_width") or []: T["full"].add(f, l)
        dv = l.get("dividers") or {}
        if len(row1) > 1: vmulti += 1; vdiv += dv.get("vertical", "none") != "none"
        if any(len(s["blocks"]) > 1 for s in ss) or l.get("grid") in ("rows", "grid"): hstack += 1; hdiv += dv.get("horizontal", "none") != "none"
        for c in l.get("connectors") or []:
            if isinstance(c, dict): T["conn"].add(f"{fam(str(c.get('from')))} -> {fam(str(c.get('to')))} ({c.get('kind')})", l)
    g = {"n_slides": N, "n_sections": S,
         "grid": {k: v / N for k, v in T["grid"].n.items()}, "sections_per_slide": {k: v / N for k, v in T["nsec"].n.items()},
         "sections_by_blocks": {str(k): {str(a): b / sum(c.values()) for a, b in c.items()} for k, c in sorted(blocks_vs_secs.items())},
         "header_rate": hdr / max(S, 1), "header_styles": {k: v / S for k, v in T["header"].n.items()}, "intro_rate": intro / max(S, 1),
         "grey_rate": grey / max(S, 1), "grey_by_kind": {k: grey_kind[k] / v for k, v in kind_sec.items() if v >= 3},
         "grey_position": {k: v / max(grey, 1) for k, v in T["grey_pos"].n.items()},
         "rel_width": {k: round(sum(v) / len(v), 2) for k, v in widths.items() if len(v) >= 3},
         "blocks_per_section": {k: v / S for k, v in T["nblocks"].n.items()},
         "under": {k: v for k, v in T["under"].n.most_common(20)}, "same_section": {k: v for k, v in T["pair"].n.most_common(20)},
         "vertical_divider_rate": vdiv / max(vmulti, 1), "horizontal_divider_rate": hdiv / max(hstack, 1),
         "full_width": {k: v / N for k, v in T["full"].n.items()}, "connectors": {k: v for k, v in T["conn"].n.most_common(12)}}
    return g, T


def table(rows, head="pattern"):
    return f"| {head} | n | share | evidence (deck#slide) |\n|---|---|---|---|\n" + "".join(f"| {k} | {n} | {p:.0%} | {', '.join(r)} |\n" for k, n, p, r in rows)


def notes(g, T):
    N, S = g["n_slides"], g["n_sections"]; NOTES.mkdir(parents=True, exist_ok=True)
    base = (f"Source: vision labels of {N} archive content slides (stratified over the decks), {S} sections; form `analysis/grammar/SCHEMA.md`. "
            f"Shares are of this sample: patterns under ~10% are rough. These are element-level habits to combine, not layouts to copy.\n\n")
    sb = "\n".join(f"- {k} blocks on the slide: " + ", ".join(f"{a} section(s) {b:.0%}" for a, b in sorted(v.items())) for k, v in g["sections_by_blocks"].items())
    rw = ", ".join(f"{k} {v}" for k, v in sorted(g["rel_width"].items(), key=lambda x: -x[1]))
    files = {
        "01-sections.md": ("Sections and widths", table(T["grid"].rows(N), "grid") + "\n" + table(T["nsec"].rows(N), "sections per slide") +
                           f"\nSection count by how many blocks the slide holds:\n{sb}\n\n2-column width split (narrow column's share):\n" + table(T["split2"].rows(sum(T["split2"].n.values())), "split") +
                           "\n3-column splits:\n" + table(T["split3"].rows(sum(T["split3"].n.values())), "split") +
                           f"\nRelative width of a section by what it holds (1.0 = an equal share): {rw}.\n"),
        "02-headers-intros.md": ("Section headers and intros", f"Sections with a header: {g['header_rate']:.0%}; with an intro sentence under the header: {g['intro_rate']:.0%}.\n\n" + table(T["header"].rows(S), "header style")),
        "03-stacking.md": ("What stacks in a section", "Blocks per section:\n" + table(T["nblocks"].rows(S), "blocks") + "\nTop block:\n" + table(T["top"].rows(S), "top block") +
                           "\nTop -> bottom pairs inside a section:\n" + table(T["under"].rows(sum(T["under"].n.values()), 15), "pair") +
                           "\nBlocks that share a section (any order):\n" + table(T["pair"].rows(sum(T["pair"].n.values()), 12), "pair")),
        "04-grey-dividers.md": ("Grey boxes and dividers", f"Sections on a grey box: {g['grey_rate']:.0%}. Vertical divider on multi-column slides: {g['vertical_divider_rate']:.0%}; horizontal divider where blocks stack: {g['horizontal_divider_rate']:.0%}.\n\n"
                                 "Grey rate by block kind (share of sections holding that kind that are grey): " + ", ".join(f"{k} {v:.0%}" for k, v in sorted(g["grey_by_kind"].items(), key=lambda x: -x[1])) +
                                 "\n\nWhere the grey section sits:\n" + table(T["grey_pos"].rows(sum(T["grey_pos"].n.values())), "position") + "\nWhat sits on grey:\n" + table(T["grey_kind"].rows(sum(T["grey_kind"].n.values())), "kind")),
        "05-connections.md": ("Full-width elements and connectors", "Full-width elements (share of slides):\n" + table(T["full"].rows(N), "element") + "\nConnectors between blocks:\n" + table(T["conn"].rows(sum(T["conn"].n.values()), 12), "connector")),
    }
    for f, (t, body) in files.items(): (NOTES / f).write_text(HEAD + f"# {t}\n\n" + base + body, "utf8")
    (NOTES / "README.md").write_text(HEAD + "# Slide grammar (archive patterns)\n\nRead these when choosing a composition: they say how archive slides combine sections, blocks, headers, intros, grey boxes, dividers and connectors. Use them as habits and frequencies; the layout comes from the content.\n\n" +
                                     "".join(f"- [{t}]({f})\n" for f, (t, _) in files.items()), "utf8")


def agree(a_path=GD / "labels_1.json", b_path=GD / "verify_1.json"):
    """Field agreement of a labeller against a reference labelling of the same slides."""
    A = {l["id"]: l for l in json.loads(Path(a_path).read_text("utf8"))}; B = {l["id"]: l for l in json.loads(Path(b_path).read_text("utf8"))}
    c = collections.Counter(); n = 0
    for k, b in B.items():
        a = A.get(k)
        if not a: continue
        n += 1; sa, sb = a.get("sections") or [], b.get("sections") or []
        c["grid"] += a.get("grid") == b.get("grid"); c["section count"] += len(sa) == len(sb)
        fa = collections.Counter(fam(x) for s in sa for x in s.get("blocks") or []); fb = collections.Counter(fam(x) for s in sb for x in s.get("blocks") or [])
        c["block kinds (overlap >= 70%)"] += sum((fa & fb).values()) / max(sum((fa | fb).values()), 1) >= .7
        c["vertical divider"] += ((a.get("dividers") or {}).get("vertical", "none") != "none") == ((b.get("dividers") or {}).get("vertical", "none") != "none")
        c["any grey"] += any(s.get("grey_box") for s in sa) == any(s.get("grey_box") for s in sb)
        c["any intro"] += any(s.get("intro") for s in sa) == any(s.get("intro") for s in sb)
        c["header share +-25pt"] += abs(sum(s.get("header", "none") != "none" for s in sa) / max(len(sa), 1) - sum(s.get("header", "none") != "none" for s in sb) / max(len(sb), 1)) <= .25
    return n, {k: v / max(n, 1) for k, v in c.items()}


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf8")
    if "--agree" in sys.argv:
        n, r = agree(); print(f"{n} slides"); [print(f"  {k}: {v:.0%}") for k, v in r.items()]; sys.exit()
    labs = load(); g, T = stats(labs); OUT.write_text(json.dumps(g, ensure_ascii=False, indent=1), "utf8"); notes(g, T)
    print(f"{g['n_slides']} slides, {g['n_sections']} sections -> {OUT.relative_to(ROOT)}, {NOTES.relative_to(ROOT)}/")
