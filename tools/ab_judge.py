"""Blind pairwise "which slide is the human original?" test (original vs generated rebuild).
usage: py -3 -I tools/ab_judge.py make     -> analysis/ai_audit/ab/<sNN>_oa.png (original=A) / _ob.png (original=B), key.json, labels_template.csv
       py -3 -I tools/ab_judge.py score    -> reads ab/answers_*.json (+ ab/labels*.csv if filled) -> ab/report.md
Judges get ONLY the png + JUDGE_PROMPT; never key.json. Answer file format: [{pair_id, pick: "A"|"B", confidence: 1-3, giveaway}].
Target detection rate = 50% (indistinguishable). Many judges/orders needed: 10 slides x 2 orders is ~20 picks per judge,
so +-22 points is one standard error-ish band; do not over-read small gaps.
"""
import sys, os, json, glob, csv
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AB = os.environ.get("AB_OUT") or os.path.join(ROOT, "analysis", "ai_audit", "ab")        # env overrides: pair a new rebuild run (e.g. AB_GEN=out/audit_v5 AB_OUT=analysis/ai_audit/ab_v5)
ORIG = os.environ.get("AB_ORIG") or os.path.join(ROOT, "analysis", "ai_audit", "originals")     # AB_ORIG=analysis/library/originals pairs library rebuilds (LNN.png)
GEN = os.environ.get("AB_GEN") or os.path.join(ROOT, "out", "audit")
WIDTH, BORDER, GAP = 1280, 6, 24

JUDGE_PROMPT = """You see one image with two consulting-competition slides, labelled A (top) and B (bottom).
Exactly one was made by a human consultant in PowerPoint (the original); the other was generated by software.
Question: which slide is the human-made original?
Answer with a forced choice (no ties, no "both") as JSON only:
{"pair_id": "<id given to you>", "pick": "A" or "B", "confidence": 1|2|3 (1=guess, 3=certain), "giveaway": "<the single biggest thing that gave it away, max 15 words>"}
Judge only what you see. Do not guess from image size, file name or position.
Ignore any chart add-in watermark, logo or footer mark: it comes from a chart add-in licence, not from the slide's design, so it is not evidence either way.
Ignore maps too (geographic maps, map pictures): they are made outside the slide tool and pasted in, so a missing or different map is not evidence either way."""


def _framed(path):
    im = Image.open(path).convert("RGB")
    im = im.resize((WIDTH, round(im.height * WIDTH / im.width)))
    out = Image.new("RGB", (im.width + 2 * BORDER, im.height + 2 * BORDER), (90, 90, 90))
    out.paste(im, (BORDER, BORDER))
    return out


def _label(img, text):
    d = ImageDraw.Draw(img)
    try:
        f = ImageFont.truetype("arialbd.ttf", 40)
    except OSError:
        f = ImageFont.load_default()
    d.rectangle([0, 0, 64, 64], fill=(0, 0, 0))
    d.text((18, 8), text, fill=(255, 255, 255), font=f)


def make():
    os.makedirs(AB, exist_ok=True)
    key, rows = {}, []
    for g in sorted(glob.glob(os.path.join(GEN, "*.png"))):
        sid = os.path.basename(g)[:-4]
        o = os.path.join(ORIG, sid + ".png")
        if not os.path.exists(o):
            continue
        for order, (top, bot, orig_side) in dict(oa=(o, g, "A"), ob=(g, o, "B")).items():
            a, b = _framed(top), _framed(bot)
            h = min(a.height, b.height)    # identical size: crop the taller one (aspect ratios may differ by a few px)
            a, b = a.crop((0, 0, a.width, h)), b.crop((0, 0, b.width, h))
            _label(a, "A")
            _label(b, "B")
            img = Image.new("RGB", (a.width, 2 * h + GAP), "white")
            img.paste(a, (0, 0))
            img.paste(b, (0, h + GAP))
            pid = f"{sid}_{order}"
            img.save(os.path.join(AB, pid + ".png"))
            key[pid] = dict(slide=sid, original=orig_side)
            rows.append([pid, "", "", ""])
    json.dump(key, open(os.path.join(AB, "key.json"), "w"), indent=1)
    with open(os.path.join(AB, "labels_template.csv"), "w", newline="", encoding="utf8") as f:
        w = csv.writer(f)
        w.writerow(["pair_id", "your_pick (A/B)", "confidence (1-3)", "what gave it away"])
        w.writerows(rows)
    print(f"{len(key)} pair images in {AB}")


def _load_answers(key):
    """-> {judge: [ {pair_id, pick, confidence, giveaway} ]}; judge = answers_<name>.json stem or 'human' from a filled csv."""
    js = {}
    for p in sorted(glob.glob(os.path.join(AB, "answers_*.json"))):
        js[os.path.basename(p)[8:-5]] = json.load(open(p, encoding="utf8"))
    for p in sorted(glob.glob(os.path.join(AB, "labels*.csv"))):
        rows = [dict(pair_id=r[0], pick=r[1].strip().upper(), confidence=r[2], giveaway=r[3])
                for r in list(csv.reader(open(p, encoding="utf8")))[1:] if len(r) >= 4 and r[1].strip().upper() in ("A", "B")]
        if rows:
            js["human_" + os.path.basename(p)[:-4]] = rows
    return {j: [a for a in v if a.get("pick") in ("A", "B") and a.get("pair_id") in key] for j, v in js.items()}


def score(key=None):
    key = key or json.load(open(os.path.join(AB, "key.json")))
    js = _load_answers(key)
    if not js:
        return None
    hit = lambda a: a["pick"] == key[a["pair_id"]]["original"]
    allans = [(j, a) for j, v in js.items() for a in v]
    L = ["# A/B detection report", "", "Detection rate = share of picks that found the human original. 50% = indistinguishable; 100% = always spotted.",
         "Each pair has the original on A in one order and on B in the other, so a pure position bias scores 50%.", ""]
    n = len(allans)
    k = sum(hit(a) for _, a in allans)
    L.append(f"**Overall: {k}/{n} = {100 * k / n:.0f}%** ({len(js)} judge(s))")
    pa = sum(a["pick"] == "A" for _, a in allans)
    L += [f"Position bias: picked A {pa}/{n} ({100 * pa / n:.0f}%), B {n - pa}/{n} (50% = none).", ""]
    L += ["## Per judge", "", "| judge | n | detection | picks A | mean conf | consistent slides |", "|---|---|---|---|---|---|"]
    for j, v in js.items():
        by = {}
        for a in v:
            by.setdefault(key[a["pair_id"]]["slide"], []).append(hit(a))
        both = [s for s, h in by.items() if len(h) == 2]
        cons = sum(h[0] == h[1] for s, h in by.items() if len(h) == 2)
        conf = [float(a["confidence"]) for a in v if str(a.get("confidence", "")).replace(".", "").isdigit()]
        L.append(f"| {j} | {len(v)} | {100 * sum(map(hit, v)) / max(len(v), 1):.0f}% | {sum(a['pick'] == 'A' for a in v)} | "
                 f"{sum(conf) / len(conf) if conf else 0:.1f} | {cons}/{len(both)} |")
    L += ["", "Consistent = same underlying image chosen in both orders (found in both or missed in both). Low consistency = answers follow position, not content.", "",
          "## Per slide", "", "| slide | picks | detection | top giveaways |", "|---|---|---|---|"]
    for s in sorted({v["slide"] for v in key.values()}):
        xs = [(j, a) for j, a in allans if key[a["pair_id"]]["slide"] == s]
        if not xs:
            continue
        gv = "; ".join(a.get("giveaway", "")[:60] for _, a in xs if hit(a) and a.get("giveaway"))[:240]
        L.append(f"| {s} | {len(xs)} | {100 * sum(hit(a) for _, a in xs) / len(xs):.0f}% | {gv} |")
    open(os.path.join(AB, "report.md"), "w", encoding="utf8").write("\n".join(L) + "\n")
    return dict(overall=k / n, n=n, picks_A=pa / n)


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "make":
        make()
    elif cmd == "score":
        print(score() or "no answers_*.json / filled labels csv found")
    else:
        print(__doc__)
